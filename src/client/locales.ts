/**
 * Dictionary key union（从 `zh` 的 `satisfies` 字面量推导）。
 *
 * 这是本插件 10 语字典的**键真源**：`en/ja/…` 全部声明为
 * `Record<keyof typeof zh, string>`，因此任何语种漏一个键都是编译错误。
 */
export type SessionGuardKey = keyof typeof zh

